def _evidence(opp: dict, n: int = 8) -> str:
    ids = opp["ticket_ids"]
    return ", ".join(ids[:n]) + (f" (+{len(ids) - n} more)" if len(ids) > n else "")


def generate_prd(row: pd.Series, opp: dict, a: Assumptions, mc: dict | None = None) -> str:
    seg = ", ".join(f"{k}: {v}" for k, v in opp["segments"].items())
    mc_txt = (f"\n- Model-implied net value (Monte Carlo, conditional on assumptions): P10 ${mc['p10']:,.0f} / "
              f"P50 ${mc['p50']:,.0f} / P90 ${mc['p90']:,.0f}; P(net>0) = {mc['prob_positive']:.0%}") if mc else ""
    return f"""# PRD: {row['label']}
_Generated by SignalForge AI from {opp['tickets']} supporting tickets. Synthetic/demo data unless you uploaded your own._

## 1. Problem statement
{opp['unique_accounts']} unique accounts ({seg}) reported a recurring problem in **{opp['product_area']}** (avg severity {opp['avg_severity']:.1f}/5, {opp['total_frequency']} reported occurrences).

## 2. Target customer
Segments affected: {seg}. Combined unique-account ACV: ${opp['acv_sum_unique']:,.0f}.

## 3. Jobs-to-be-Done
When {opp['product_area'].lower()} behaviour blocks my workflow, help me restore reliable operation so I can keep using the product without escalations.

## 4. Proposed solution (smallest viable)
Resolve the root cause behind the clustered reports; validate with the listed evidence tickets before scoping. _Solution design is a human decision; this PRD does not invent one._

## 5. Scope / non-goals
In scope: the behaviour described by the evidence tickets. Non-goals: adjacent requests not present in the evidence.

## 6. Functional requirements & acceptance criteria
- The failure pattern in evidence tickets ({_evidence(opp, 3)}) no longer reproduces.
- Affected accounts can confirm resolution (target: all {opp['unique_accounts']} accounts contacted).

## 7. Success metrics (targets are hypotheses)
- Repeat tickets in this cluster within 60 days of launch: reduce to near zero.
- Support escalations from affected accounts.

## 8. Risks and dependencies
Evidence quality {row['confidence']:.2f}/1 (heuristic, not calibrated). Exposure is a scenario estimate, not verified churn.

## 9. Tradeoffs
Rank {int(row['final_rank'])} of the roadmap; model rank {int(row['model_rank'])}; baseline (severity x frequency) rank {int(row['baseline_rank'])}.
{('Human override rationale: ' + row['override_rationale']) if row.get('override_rationale') else ''}

## 10. Estimated economics (assumptions: exposure fraction {a.base_exposure_fraction:.0%} x severity multiplier, recovery probability {a.recovery_probability:.0%}, ${a.eng_cost_per_person_week:,.0f}/person-week)
- Potential revenue exposure: ${row['potential_revenue_exposure']:,.0f} (scenario)
- Expected recoverable value: ${row['expected_recoverable_value']:,.0f}
- Total investment: ${row['total_investment']:,.0f} ({row['effort_weeks']:.1f} person-weeks + operating)
- Net opportunity value: ${row['net_opportunity_value']:,.0f}; ROI: {('%.1fx' % row['roi']) if row['roi'] is not None else 'n/a'}{mc_txt}

## 11. Launch and validation plan
Interview 3 affected accounts, confirm root cause, ship behind a flag, measure repeat tickets. Outcomes are unmeasured until executed.

## Evidence trail
Tickets: {_evidence(opp)}
"""


def generate_memo(ranked: pd.DataFrame, a: Assumptions, portfolio: float) -> str:
    top = ranked.head(3)
    lines = "\n".join(f"{int(r.final_rank)}. **{r.label}** - net ${r.net_opportunity_value:,.0f}, {r.unique_accounts} accounts, "
                      f"{r.effort_weeks:.1f} pw, evidence {r.confidence:.2f}" for r in top.itertuples())
    pos = bool((top["net_opportunity_value"] > 0).any())
    rec = "VALIDATE" if pos else "STOP"
    return f"""# Executive Investment Summary
**Recommendation: {rec}** (modeled; validate with customer interviews before funding)

## Top 3 investments
{lines}

## Financial rationale
Portfolio exposure (no double counting): ${portfolio:,.0f} - a scenario estimate, not verified churn. Assumptions: recovery {a.recovery_probability:.0%}, exposure fraction {a.base_exposure_fraction:.0%}.

## Risks
Exposure is hypothetical; evidence quality is a heuristic; synthetic data unless replaced.

## Next experiment
Interview 3 accounts behind the #1 item to confirm the problem and willingness to stay/expand.
"""


