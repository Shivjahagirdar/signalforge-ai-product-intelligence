def _pseudo(value: str, prefix: str) -> str:
    """Stable pseudonymous id; avoids carrying usernames into the app."""
    return f"{prefix}-{hashlib.sha256(str(value).encode()).hexdigest()[:10]}"


def _fetch(url: str, max_bytes: int = MAX_FETCH_BYTES) -> bytes:
    if not url.startswith("https://"):
        raise IngestionError("Only https sources are allowed.")
    req = urllib.request.Request(url, headers={"User-Agent": "SignalForge-AI/2.0", "Range": f"bytes=0-{max_bytes - 1}"})
    try:
        with urllib.request.urlopen(req, timeout=FETCH_TIMEOUT_S) as r:  # noqa: S310 - https enforced above
            return r.read(max_bytes)
    except Exception as exc:  # noqa: BLE001
        raise IngestionError(f"Could not reach the dataset host ({type(exc).__name__}). Try again later or upload a CSV.") from exc


def _read_partial_csv(raw: bytes) -> pd.DataFrame:
    text = raw.decode("utf-8", errors="replace")
    if "\n" in text:
        text = text[: text.rfind("\n")]  # drop a truncated last line from a ranged read
    return pd.read_csv(io.StringIO(text), on_bad_lines="skip", engine="python")


# ---------------- adapters: source schema -> SignalForge schema ----------------
def _base(n: int) -> dict:
    return dict(customer_segment=["Unknown"] * n, annual_contract_value=[np.nan] * n,
                estimated_engineering_effort=[np.nan] * n, status=["open"] * n)


def adapt_app_reviews(df: pd.DataFrame, source: str = "fdroid_reviews", sample: int = 1500, seed: int = 11) -> pd.DataFrame:
    d = df.dropna(subset=["review"]).copy()
    d = d[d["review"].astype(str).str.len() >= 25]
    stars = pd.to_numeric(d["star"], errors="coerce")
    d = d[stars <= 3]  # focus on problem signal; 4-5 star praise is not a product problem
    if len(d) > sample:
        d = d.sample(sample, random_state=seed)
    n = len(d)
    out = pd.DataFrame(dict(
        ticket_id=d["id"].astype(str).values, account_id=[_pseudo(i, "reviewer") for i in d["id"]],
        product_area=d["package_name"].astype(str).str.split(".").str[-1].values,
        feedback_text=d["review"].astype(str).values,
        severity=(6 - pd.to_numeric(d["star"], errors="coerce")).clip(1, 5).values,
        frequency=[1] * n, created_at=pd.to_datetime(d["date"], errors="coerce", format="mixed").values,
        **_base(n)))
    out["source"] = source
    return out


def adapt_bitext(df: pd.DataFrame, sample: int = 1500, seed: int = 11) -> pd.DataFrame:
    d = df.dropna(subset=["instruction"]).copy()
    if len(d) > sample:
        d = d.groupby("intent", group_keys=False).apply(lambda g: g.sample(min(len(g), sample // 27 + 1), random_state=seed))
    n = len(d)
    sev = {"complaint": 4, "payment_issue": 4, "registration_problems": 4, "get_refund": 4, "track_refund": 3}
    out = pd.DataFrame(dict(
        ticket_id=[f"bitext-{i}" for i in d.index], account_id=[_pseudo(i, "customer") for i in d.index],
        product_area=d["category"].str.title().values, feedback_text=d["instruction"].astype(str).values,
        severity=[sev.get(i, 2) for i in d["intent"]], frequency=[1] * n, created_at=[pd.NaT] * n, **_base(n)))
    out["source"] = "bitext_support"
    out["ground_truth_issue"] = d["intent"].values
    return out


def adapt_github_issues(items: list[dict], repo: str) -> pd.DataFrame:
    rows = []
    for it in items:
        if "pull_request" in it:
            continue
        labels = [lb.get("name", "") for lb in it.get("labels", [])]
        body = re.sub(r"```.*?```", " ", it.get("body") or "", flags=re.S)[:1200]
        bug = any("bug" in lb.lower() for lb in labels)
        rows.append(dict(
            ticket_id=f"{repo}#{it['number']}", account_id=_pseudo(it.get("user", {}).get("login", it["number"]), "gh"),
            product_area=(labels[0] if labels else "untriaged")[:40], feedback_text=f"{it.get('title', '')}. {body}".strip(),
            severity=4 if bug else 3, frequency=1 + int(it.get("reactions", {}).get("total_count", 0)),
            created_at=it.get("created_at"), status=it.get("state", "open"),
            customer_segment="Unknown", annual_contract_value=np.nan, estimated_engineering_effort=np.nan))
    if not rows:
        raise IngestionError("No issues returned (repository may be empty, private, or rate-limited).")
    out = pd.DataFrame(rows)
    out["source"] = "github_issues"
    return out


def load_public(key: str, github_repo: str | None = None) -> pd.DataFrame:
    """Fetch + adapt a registered public dataset. Raises IngestionError with a user-safe message."""
    if key == "fdroid_reviews":
        return adapt_app_reviews(_read_partial_csv(_fetch(REGISTRY[key].url)))
    if key == "bitext_support":
        return adapt_bitext(_read_partial_csv(_fetch(REGISTRY[key].url, 12 * 1024 * 1024)))
    if key == "github_issues":
        if not github_repo or not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", github_repo):
            raise IngestionError("Enter a public repository as owner/name, e.g. streamlit/streamlit.")
        items: list[dict] = []
        for page in (1, 2, 3):
            raw = _fetch(f"https://api.github.com/repos/{github_repo}/issues?state=all&per_page=100&page={page}", 4 * 1024 * 1024)
            batch = json.loads(raw)
            if not isinstance(batch, list):
                raise IngestionError(f"GitHub API: {batch.get('message', 'unexpected response')}")
            items += batch
            if len(batch) < 100:
                break
        return adapt_github_issues(items, github_repo)
    raise IngestionError(f"Unknown dataset '{key}'.")


# ---------------- generic uploads: schema detection + column mapping ----------------
_CANDIDATES = {
    "feedback_text": ["feedback_text", "feedback", "text", "review", "body", "comment", "description", "message", "content",
                      "instruction", "summary", "title"],
    "ticket_id": ["ticket_id", "id", "issue_id", "review_id", "number", "key"],
    "account_id": ["account_id", "account", "customer_id", "company", "org", "user_id", "author"],
    "annual_contract_value": ["annual_contract_value", "acv", "arr", "contract_value", "mrr_annual"],
    "severity": ["severity", "priority", "sev"],
    "rating": ["rating", "star", "stars", "score"],
    "created_at": ["created_at", "date", "created", "timestamp", "time"],
    "customer_segment": ["customer_segment", "segment", "tier", "plan"],
    "product_area": ["product_area", "area", "component", "category", "module", "package_name"],
}


def detect_mapping(columns: list[str]) -> dict[str, str]:
    low = {c.lower().strip(): c for c in columns}
    m = {}
    for target, cands in _CANDIDATES.items():
        for c in cands:
            if c in low and low[c] not in m.values():
                m[target] = low[c]
                break
    return m


def coerce_to_schema(df: pd.DataFrame, mapping: dict[str, str] | None = None) -> tuple[pd.DataFrame, list[str]]:
    """Map an arbitrary feedback table onto the SignalForge schema. Missing financial fields stay missing."""
    if all(c in df.columns for c in REQUIRED):
        return df, []
    mapping = mapping or detect_mapping(list(df.columns))
    if "feedback_text" not in mapping:
        raise IngestionError("Couldn't find a text column. Name one of: feedback_text, text, review, body, comment, description.")
    notes, n = [], len(df)
    out = pd.DataFrame({"feedback_text": df[mapping["feedback_text"]].astype("string")})
    out["ticket_id"] = df[mapping["ticket_id"]].astype(str) if "ticket_id" in mapping else [f"row-{i + 1}" for i in range(n)]
    if "account_id" in mapping:
        out["account_id"] = df[mapping["account_id"]].astype(str).map(lambda v: _pseudo(v, "acct"))
    else:
        out["account_id"] = out["ticket_id"].map(lambda v: _pseudo(v, "anon"))
        notes.append("No account column: each record treated as a separate anonymous account.")
    out["annual_contract_value"] = pd.to_numeric(df[mapping["annual_contract_value"]], errors="coerce") if "annual_contract_value" in mapping else np.nan
    if "annual_contract_value" not in mapping:
        notes.append("No revenue column: ACV left UNKNOWN (not zero). Economics needs an explicit assumption.")
    if "severity" in mapping:
        out["severity"] = df[mapping["severity"]]
    elif "rating" in mapping:
        r = pd.to_numeric(df[mapping["rating"]], errors="coerce")
        out["severity"] = (6 - r).clip(1, 5)
        notes.append(f"Severity derived from '{mapping['rating']}' (6 - rating).")
    else:
        out["severity"] = 3
        notes.append("No severity/rating column: severity defaulted to 3 for all rows.")
    out["frequency"] = 1
    out["created_at"] = df[mapping["created_at"]] if "created_at" in mapping else pd.NaT
    out["customer_segment"] = df[mapping["customer_segment"]] if "customer_segment" in mapping else "Unknown"
    out["product_area"] = df[mapping["product_area"]].astype(str) if "product_area" in mapping else "general"
    out["status"] = "open"
    out["estimated_engineering_effort"] = np.nan
    notes.append("Column mapping: " + ", ".join(f"{k}<-{v}" for k, v in mapping.items()))
    return out, notes


def data_quality(df: pd.DataFrame) -> dict:
    """Simple, explainable 0-100 data-quality score with its components."""
    n = max(len(df), 1)
    text_len = df["feedback_text"].astype(str).str.split().str.len()
    comp = {
        "text_present": float(df["feedback_text"].astype(str).str.strip().ne("").mean()),
        "acv_coverage": float(pd.to_numeric(df.get("annual_contract_value"), errors="coerce").notna().mean()),
        "date_coverage": float(pd.to_datetime(df.get("created_at"), errors="coerce").notna().mean()) if "created_at" in df else 0.0,
        "segment_known": float((df.get("customer_segment", pd.Series(["Unknown"] * n)) != "Unknown").mean()),
        "effort_coverage": float(pd.to_numeric(df.get("estimated_engineering_effort"), errors="coerce").notna().mean()),
        "substantive_text": float((text_len >= 5).mean()),
    }
    w = {"text_present": 0.25, "acv_coverage": 0.2, "date_coverage": 0.1, "segment_known": 0.1, "effort_coverage": 0.1, "substantive_text": 0.25}
    score = 100 * sum(comp[k] * w[k] for k in w)
    return dict(score=round(score, 1), components=comp, rows=len(df), median_words=float(text_len.median()) if n else 0.0)
